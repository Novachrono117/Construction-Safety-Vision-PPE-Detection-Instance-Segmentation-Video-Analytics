def _parse_metrics(data: Any) -> SegmentationMetricHierarchy:
    """Parse and validate the predeclared segmentation metric hierarchy.

    Args:
        data: Raw ``metrics`` mapping.

    Returns:
        The parsed hierarchy.

    Raises:
        SegmentationExperimentConfigError: If it is malformed, the primary
            metric is not the frozen mask summary metric, a box metric has been
            promoted into the mask sections, or a composite score is declared.
    """
    if not isinstance(data, Mapping):
        msg = "segmentation_baseline.metrics: must be a mapping"
        raise SegmentationExperimentConfigError(msg)
    try:
        check_keys(data, required=REQUIRED_METRIC_KEYS, context="segmentation_baseline.metrics")
    except ConfigError as exc:
        raise SegmentationExperimentConfigError(str(exc)) from exc

    primary = str(data["primary"])
    if primary != PRIMARY_METRIC:
        msg = (
            f"segmentation_baseline.metrics.primary must be {PRIMARY_METRIC!r}, got {primary!r}. "
            "The headline metric of a segmentation experiment is the mask summary metric; "
            "anything else would have to be argued for in advance, not selected after results."
        )
        raise SegmentationExperimentConfigError(msg)

    if data["composite_box_mask_score"] is not False:
        msg = (
            "segmentation_baseline.metrics.composite_box_mask_score must be false. A combined "
            "box-plus-mask score invented for this project would let a weak mask result hide "
            "behind a strong box one; box and mask metrics are reported side by side instead."
        )
        raise SegmentationExperimentConfigError(msg)

    for name in ("secondary_mask", "box_from_segmenter", "per_class_mask", "per_class_box"):
        values = data[name]
        if not isinstance(values, list) or not values:
            msg = f"segmentation_baseline.metrics.{name}: must be a non-empty list"
            raise SegmentationExperimentConfigError(msg)
        if primary in values:
            msg = f"segmentation_baseline.metrics: the primary metric must not repeat in {name!r}"
            raise SegmentationExperimentConfigError(msg)

    for name in ("secondary_mask", "per_class_mask"):
        offending = [str(value) for value in data[name] if not str(value).startswith("mask_")]
        if offending:
            msg = (
                f"segmentation_baseline.metrics.{name} must contain mask metrics only, found "
                f"{offending}. Box metrics belong in box_from_segmenter and per_class_box, so "
                "the two families cannot be read as one."
            )
            raise SegmentationExperimentConfigError(msg)
    for name in ("box_from_segmenter", "per_class_box"):
        offending = [str(value) for value in data[name] if not str(value).startswith("box_")]
        if offending:
            msg = (
                f"segmentation_baseline.metrics.{name} must contain box metrics only, found "
                f"{offending}."
            )
            raise SegmentationExperimentConfigError(msg)

    supported_macro = str(data["supported_macro"])
    if supported_macro != SUPPORTED_MACRO_MASK_METRIC:
        msg = (
            f"segmentation_baseline.metrics.supported_macro must be "
            f"{SUPPORTED_MACRO_MASK_METRIC!r}, got {supported_macro!r}"
        )
        raise SegmentationExperimentConfigError(msg)

    artifacts = data["artifacts"]
    if not isinstance(artifacts, list) or not artifacts:
        msg = "segmentation_baseline.metrics.artifacts: must be a non-empty list"
        raise SegmentationExperimentConfigError(msg)

    return SegmentationMetricHierarchy(
        primary=primary,
        secondary_mask=tuple(str(value) for value in data["secondary_mask"]),
        box_from_segmenter=tuple(str(value) for value in data["box_from_segmenter"]),
        per_class_mask=tuple(str(value) for value in data["per_class_mask"]),
        per_class_box=tuple(str(value) for value in data["per_class_box"]),
        supported_macro=supported_macro,
        artifacts=tuple(str(value) for value in artifacts),
    )


def _parse_adapter(data: Any) -> dict[str, Any]:
    """Parse and validate the adapter declaration.

    Args:
        data: Raw ``adapter`` mapping.

    Returns:
        The validated mapping.

    Raises:
        SegmentationExperimentConfigError: If it is malformed, a digest is not a
            digest, the adapter claims to be canonical, or the declared
            cardinality does not add up.
    """
    if not isinstance(data, Mapping):
        msg = "segmentation_baseline.adapter: must be a mapping"
        raise SegmentationExperimentConfigError(msg)
    try:
        check_keys(data, required=REQUIRED_ADAPTER_KEYS, context="segmentation_baseline.adapter")
    except ConfigError as exc:
        raise SegmentationExperimentConfigError(str(exc)) from exc

    if str(data["role"]) != ADAPTER_ROLE:
        msg = (
            f"segmentation_baseline.adapter.role must be {ADAPTER_ROLE!r}, got "
            f"{data['role']!r}. The YOLO labels are a lossy derived view; the canonical COCO "
            "instance segmentation remains the ground truth."
        )
        raise SegmentationExperimentConfigError(msg)

    for name in (
        "audit_manifest_sha256",
        "labels_train_sha256",
        "labels_validation_sha256",
        "labels_development_sha256",
        "image_membership_sha256",
    ):
        value = str(data[name])
        if not SHA256_PATTERN.match(value):
            msg = f"segmentation_baseline.adapter.{name} is not a SHA-256 digest: {value!r}"
            raise SegmentationExperimentConfigError(msg)

    if data["all_instances_retained"] is not True:
        msg = (
            "segmentation_baseline.adapter.all_instances_retained must be true. Excluding "
            "instances after observing adapter fidelity would change the canonical modelling "
            "population in response to a model-format limitation."
        )
        raise SegmentationExperimentConfigError(msg)
    if str(data["fidelity_based_filtering"]) != "NONE":
        msg = (
            "segmentation_baseline.adapter.fidelity_based_filtering must be 'NONE', got "
            f"{data['fidelity_based_filtering']!r}"
        )
        raise SegmentationExperimentConfigError(msg)

    counts = {
        name: data[name]
        for name in (
            "instances",
            "train_instances",
            "validation_instances",
            "train_images",
            "validation_images",
            "negative_images",
        )
    }
    for name, value in counts.items():
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            msg = f"segmentation_baseline.adapter.{name} must be a non-negative integer"
            raise SegmentationExperimentConfigError(msg)
    if counts["train_instances"] + counts["validation_instances"] != counts["instances"]:
        msg = (
            f"segmentation_baseline.adapter: {counts['train_instances']} train plus "
            f"{counts['validation_instances']} validation instances do not sum to the declared "
            f"{counts['instances']}"
        )
        raise SegmentationExperimentConfigError(msg)

    return dict(data)


def _parse_block(raw: Mapping[str, Any], *, key: str, required: tuple[str, ...]) -> dict[str, Any]:
    """Parse and validate one exhaustively-declared argument block.

    Args:
        raw: The whole parsed document.
        key: The block's key.
        required: Every argument the block must state.

    Returns:
        The validated mapping.

    Raises:
        SegmentationExperimentConfigError: If it is not a mapping, or a required
            argument is missing or unknown.
    """
    block = raw[key]
    if not isinstance(block, Mapping):
        msg = f"segmentation_baseline.{key}: must be a mapping"
        raise SegmentationExperimentConfigError(msg)
    try:
        check_keys(block, required=required, context=f"segmentation_baseline.{key}")
    except ConfigError as exc:
        raise SegmentationExperimentConfigError(str(exc)) from exc
    return dict(block)


def _check_checkpoint_policy(raw: Mapping[str, Any]) -> None:
    """Validate the reviewed checkpoint-selection decision.

    The point of these checks is narrow and worth stating. Ultralytics selects a
    segmentation ``best.pt`` on a composite of box and mask mAP@0.50:0.95, which
    is **not** this project's primary reporting metric. Phase 8B reviewed that
    and accepted it. What must never happen afterwards is the divergence being
    quietly closed - either by relabelling the composite as the headline metric,
    or by swapping in a mask-only selector once S0's numbers are visible. Both
    are refused here rather than discouraged in prose.

    Args:
        raw: The parsed mapping.

    Raises:
        SegmentationExperimentConfigError: If any part of the decision has been
            altered.
    """
    expected = {
        "checkpoint_selection_policy": CHECKPOINT_SELECTION_POLICY,
        "checkpoint_selection_review_status": CHECKPOINT_SELECTION_REVIEW_STATUS,
        "checkpoint_selection_semantics": CHECKPOINT_SELECTION_SEMANTICS,
        "primary_scientific_reporting_metric": PRIMARY_SCIENTIFIC_REPORTING_METRIC,
    }
    for name, value in expected.items():
        if str(raw[name]) != value:
            msg = f"segmentation_baseline.{name} must be {value!r}, got {raw[name]!r}"
            raise SegmentationExperimentConfigError(msg)

    weights = {
        "checkpoint_selection_box_component_weight": CHECKPOINT_SELECTION_BOX_WEIGHT,
        "checkpoint_selection_mask_component_weight": CHECKPOINT_SELECTION_MASK_WEIGHT,
    }
    for name, value in weights.items():
        if isinstance(raw[name], bool) or float(raw[name]) != value:
            msg = (
                f"segmentation_baseline.{name} must be {value}, got {raw[name]!r}. The native "
                "fitness weights its two mAP@0.50:0.95 terms equally; recording anything else "
                "would misdescribe the mechanism that picks the checkpoint."
            )
            raise SegmentationExperimentConfigError(msg)

    if raw["selection_metric_equals_primary_reporting_metric"] is not False:
        msg = (
            "segmentation_baseline.selection_metric_equals_primary_reporting_metric must be "
            "false. The checkpoint is selected on a box-plus-mask composite while the headline "
            "metric is mask mAP@0.50:0.95; those are different things, and the difference is "
            "recorded deliberately rather than smoothed over."
        )
        raise SegmentationExperimentConfigError(msg)

    rationale = raw["checkpoint_selection_rationale"]
    if not isinstance(rationale, list) or not rationale:
        msg = "segmentation_baseline.checkpoint_selection_rationale: must be a non-empty list"
        raise SegmentationExperimentConfigError(msg)
    for entry in rationale:
        if "superior" in str(entry).lower() and "not " not in str(entry).lower():
            msg = (
                "segmentation_baseline.checkpoint_selection_rationale claims the composite "
                "fitness is superior. It is an accepted baseline protocol choice, and no "
                "experiment in this project compares it against mask-only selection."
            )
            raise SegmentationExperimentConfigError(msg)

    constraint = str(raw["checkpoint_selection_future_constraint"])
    if CHECKPOINT_SELECTION_POLICY not in constraint:
        msg = (
            "segmentation_baseline.checkpoint_selection_future_constraint must name "
            f"{CHECKPOINT_SELECTION_POLICY!r}: every experiment later compared with S0 inherits "
            "this checkpoint policy unless a new protocol is frozen beforehand."
        )
        raise SegmentationExperimentConfigError(msg)


def load_segmentation_baseline_config(path: str | Path) -> SegmentationBaselineConfig:
    """Load and validate a segmentation experiment protocol.

    Args:
        path: Configuration file.

    Returns:
        The parsed protocol.

    Raises:
        SegmentationExperimentConfigError: If the file is missing, malformed,
            names the protected split, declares a metric hierarchy outside the
            frozen shape, or declares the same framework argument twice.
    """
    config_path = Path(path).expanduser()
    if not config_path.is_file():
        msg = f"Segmentation baseline configuration not found: {config_path.name}"
        raise SegmentationExperimentConfigError(msg)
    try:
        raw = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        msg = f"Segmentation baseline configuration is not valid YAML: {config_path.name} ({exc})"
        raise SegmentationExperimentConfigError(msg) from exc
    if not isinstance(raw, Mapping):
        msg = f"Segmentation baseline configuration must be a mapping: {config_path.name}"
        raise SegmentationExperimentConfigError(msg)

    try:
        _check_top_level(raw)
    except ConfigError as exc:
        raise SegmentationExperimentConfigError(str(exc)) from exc

    if int(raw["schema_version"]) != CONFIG_SCHEMA_VERSION:
        msg = (
            f"segmentation_baseline.schema_version must be {CONFIG_SCHEMA_VERSION}, got "
            f"{raw['schema_version']!r}"
        )
        raise SegmentationExperimentConfigError(msg)

    experiment_id = str(raw["experiment_id"])
    if not EXPERIMENT_ID_PATTERN.match(experiment_id):
        msg = (
            f"segmentation_baseline.experiment_id {experiment_id!r} is not a valid identifier; "
            "expected a task letter followed by a number, such as 'S0'"
        )
        raise SegmentationExperimentConfigError(msg)

    if str(raw["task"]) != TASK:
        msg = f"segmentation_baseline.task must be {TASK!r}, got {raw['task']!r}"
        raise SegmentationExperimentConfigError(msg)

    if str(raw["canonical_ground_truth"]) != CANONICAL_GROUND_TRUTH:
        msg = (
            f"segmentation_baseline.canonical_ground_truth must be {CANONICAL_GROUND_TRUTH!r}, "
            f"got {raw['canonical_ground_truth']!r}"
        )
        raise SegmentationExperimentConfigError(msg)

    splits = raw["splits"]
    if not isinstance(splits, list) or tuple(splits) != DEVELOPMENT_SPLITS:
        msg = (
            f"segmentation_baseline.splits must be exactly {list(DEVELOPMENT_SPLITS)}, got "
            f"{splits!r}. An experiment protocol never names the holdout."
        )
        raise SegmentationExperimentConfigError(msg)
    if _contains_forbidden_split(dict(raw)):
        msg = (
            "segmentation_baseline references the protected split. The holdout may not appear "
            "in a training protocol, a dataset descriptor or a metric declaration."
        )
        raise SegmentationExperimentConfigError(msg)

    training = _parse_block(raw, key="training", required=REQUIRED_TRAINING_KEYS)
    segmentation_arguments = _parse_block(
        raw, key="segmentation_arguments", required=REQUIRED_SEGMENTATION_KEYS
    )
    augmentation_arguments = _parse_block(
        raw, key="augmentation_arguments", required=REQUIRED_AUGMENTATION_KEYS
    )

    overlapping = (
        (set(training) & set(segmentation_arguments))
        | (set(training) & set(augmentation_arguments))
        | (set(segmentation_arguments) & set(augmentation_arguments))
    )
    if overlapping:
        msg = (
            f"segmentation_baseline declares {sorted(overlapping)} in more than one argument "
            "block. Each framework argument is stated exactly once, so no precedence rule is "
            "needed to know what ran."
        )
        raise SegmentationExperimentConfigError(msg)

    if str(training["augmentation"]) != AUGMENTATION_POLICY:
        msg = (
            f"segmentation_baseline.training.augmentation must be {AUGMENTATION_POLICY!r}, got "
            f"{training['augmentation']!r}"
        )
        raise SegmentationExperimentConfigError(msg)
    if str(raw["augmentation_policy"]) != AUGMENTATION_POLICY:
        msg = (
            f"segmentation_baseline.augmentation_policy must be {AUGMENTATION_POLICY!r}, got "
            f"{raw['augmentation_policy']!r}"
        )
        raise SegmentationExperimentConfigError(msg)

    _check_checkpoint_policy(raw)

    checkpoint_selection = str(raw["checkpoint_selection"])
    if CHECKPOINT_RULE not in checkpoint_selection:
        msg = (
            f"segmentation_baseline.checkpoint_selection must name {CHECKPOINT_RULE!r}. The "
            "checkpoint rule is fixed before training so no checkpoint is chosen after the fact."
        )
        raise SegmentationExperimentConfigError(msg)

    for name in ("class_map_sha256", "split_assignment_sha256"):
        if not SHA256_PATTERN.match(str(raw[name])):
            msg = f"segmentation_baseline.{name} is not a SHA-256 digest: {raw[name]!r}"
            raise SegmentationExperimentConfigError(msg)

    return SegmentationBaselineConfig(
        schema_version=int(raw["schema_version"]),
        experiment_id=experiment_id,
        task=TASK,
        description=str(raw["description"]),
        architecture=str(raw["architecture"]),
        model=str(raw["model"]),
        weights=str(raw["weights"]),
        weight_identifier=str(raw["weight_identifier"]),
        fallback_architecture=str(raw["fallback_architecture"]),
        fallback_status=str(raw["fallback_status"]),
        canonical_ground_truth=CANONICAL_GROUND_TRUTH,
        dataset_config=str(raw["dataset_config"]),
        adapter=_parse_adapter(raw["adapter"]),
        class_map_sha256=str(raw["class_map_sha256"]),
        split_assignment_sha256=str(raw["split_assignment_sha256"]),
        splits=DEVELOPMENT_SPLITS,
        seed=int(raw["seed"]),
        device_requirement=str(raw["device_requirement"]),
        training=training,
        segmentation_arguments=segmentation_arguments,
        augmentation_policy=AUGMENTATION_POLICY,
        augmentation_arguments=augmentation_arguments,
        batch_decision=str(raw["batch_decision"]),
        checkpoint_selection=checkpoint_selection,
        checkpoint_selection_policy=CHECKPOINT_SELECTION_POLICY,
        checkpoint_selection_review_status=CHECKPOINT_SELECTION_REVIEW_STATUS,
        checkpoint_selection_semantics=CHECKPOINT_SELECTION_SEMANTICS,
        checkpoint_selection_box_component_weight=CHECKPOINT_SELECTION_BOX_WEIGHT,
        checkpoint_selection_mask_component_weight=CHECKPOINT_SELECTION_MASK_WEIGHT,
        primary_scientific_reporting_metric=PRIMARY_SCIENTIFIC_REPORTING_METRIC,
        selection_metric_equals_primary_reporting_metric=False,
        checkpoint_selection_rationale=tuple(
            str(entry) for entry in raw["checkpoint_selection_rationale"]
        ),
        checkpoint_selection_future_constraint=str(raw["checkpoint_selection_future_constraint"]),
        metrics=_parse_metrics(raw["metrics"]),
        rare_class=str(raw["rare_class"]),
        rare_class_limitation=str(raw["rare_class_limitation"]),
        test_policy=str(raw["test_policy"]),
    )
