"""The frozen protocol of one segmentation experiment.

Phase 8B. Sibling of :mod:`construction_safety_vision.experiment`, deliberately
not an extension of it: ``configs/detection_baseline.yaml`` is the protocol D0,
D1 and D2 inherit, its digest is recorded in three committed manifests, and
widening its parser to accept segmentation keys would put an untested change
underneath a frozen comparison. So segmentation gets its own schema, and the
detection one keeps meaning exactly what it meant when the detector was frozen.

Four things are enforced here rather than trusted.

**No protocol may name the holdout.** Checked recursively over the whole parsed
document, keys included, because a training configuration is one of the easiest
places for the protected split to enter by accident.

**The metric hierarchy is fixed, ordered, and separates mask from box.** A
segmentation model reports both, and letting them merge is how a weak mask
result hides behind a strong box one. The primary metric must be the mask
summary metric, box metrics are declared in their own section, and a composite
box-plus-mask score is refused outright rather than left available for later.

**The adapter is named by digest, not by path.** A segmentation protocol that
cannot say which label bytes it trained on cannot be reproduced, and a path can
point at regenerated bytes without anything noticing.

**The rare-class support rule is the one Phase 7 froze.** Its thresholds are
imported from :mod:`construction_safety_vision.detection_comparison` and the
mask macro metric is derived from that module's detection counterpart, rather
than either being restated here, so the segmentation phase cannot quietly
acquire a friendlier threshold or a differently-defined macro.
"""

