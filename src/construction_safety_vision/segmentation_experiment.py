class SegmentationExperimentConfigError(ConfigError):
    """Raised when a segmentation protocol is missing, malformed or unsafe."""


@dataclass(frozen=True)
class SegmentationMetricHierarchy:
    """The metrics a segmentation experiment commits to reporting, in order.

    Attributes:
        primary: The single metric that decides the headline result.
        secondary_mask: Supporting global mask metrics.
        box_from_segmenter: Box metrics the segmentation model also produces,
            reported separately and never merged into the mask result.
        per_class_mask: Mask metrics reported for each class.
        per_class_box: Box metrics reported for each class.
        supported_macro: The macro metric defined over the frozen support rule's
            admitted classes.
        artifacts: Diagnostic outputs preserved alongside the numbers.
    """

    primary: str
    secondary_mask: tuple[str, ...]
    box_from_segmenter: tuple[str, ...]
    per_class_mask: tuple[str, ...]
    per_class_box: tuple[str, ...]
    supported_macro: str
    artifacts: tuple[str, ...]

    def as_dict(self) -> dict[str, Any]:
        """Serialise for the manifest and the protocol fingerprint.

        Returns:
            A JSON-serialisable mapping.
        """
        return {
            "primary": self.primary,
            "secondary_mask": list(self.secondary_mask),
            "box_from_segmenter": list(self.box_from_segmenter),
            "per_class_mask": list(self.per_class_mask),
            "per_class_box": list(self.per_class_box),
            "supported_macro": self.supported_macro,
            "artifacts": list(self.artifacts),
            "composite_box_mask_score": False,
        }


@dataclass(frozen=True)
class SegmentationBaselineConfig:
    """The frozen protocol of one segmentation experiment.

    Attributes:
        schema_version: Version of this configuration schema.
        experiment_id: Stable identifier, e.g. ``S0``.
        task: Task name.
        description: What question the experiment answers.
        architecture: The selected segmentation architecture.
        model: Model family and size.
        weights: Whether training starts from pretrained weights.
        weight_identifier: The exact pretrained checkpoint name.
        fallback_architecture: The recorded, not-selected alternative.
        fallback_status: Its status.
        canonical_ground_truth: The authoritative annotation format.
        dataset_config: Repository-relative adapter dataset descriptor.
        adapter: The derived adapter's role, digests and cardinality.
        class_map_sha256: The frozen canonical class map's digest.
        split_assignment_sha256: The frozen split's digest.
        splits: Splits the experiment may read.
        seed: Master seed.
        device_requirement: What hardware the full run requires.
        training: The complete general hyperparameter set.
        segmentation_arguments: Segmentation-specific framework arguments.
        augmentation_policy: The augmentation policy name.
        augmentation_arguments: Effective augmentation values.
        batch_decision: Why the batch size is what it is, recorded in advance.
        checkpoint_selection: The rule naming which checkpoint is reported.
        checkpoint_selection_policy: The mechanism that selects ``best.pt``.
        checkpoint_selection_review_status: When that mechanism was accepted.
        checkpoint_selection_semantics: What the native fitness sums.
        checkpoint_selection_box_component_weight: Its box term's weight.
        checkpoint_selection_mask_component_weight: Its mask term's weight.
        primary_scientific_reporting_metric: The headline metric, which is not
            the selection mechanism.
        selection_metric_equals_primary_reporting_metric: Required ``False``, so
            the divergence is recorded rather than reconstructed by a reader.
        checkpoint_selection_rationale: Why the native fitness was kept.
        checkpoint_selection_future_constraint: What later experiments inherit.
        metrics: The predeclared metric hierarchy.
        rare_class: The class whose results carry a small-sample limitation.
        rare_class_limitation: The limitation, recorded before training.
        test_policy: The holdout's status under this protocol.
    """

    schema_version: int
    experiment_id: str
    task: str
    description: str
    architecture: str
    model: str
    weights: str
    weight_identifier: str
    fallback_architecture: str
    fallback_status: str
    canonical_ground_truth: str
    dataset_config: str
    adapter: dict[str, Any]
    class_map_sha256: str
    split_assignment_sha256: str
    splits: tuple[str, ...]
    seed: int
    device_requirement: str
    training: dict[str, Any]
    segmentation_arguments: dict[str, Any]
    augmentation_policy: str
    augmentation_arguments: dict[str, Any]
    batch_decision: str
    checkpoint_selection: str
    checkpoint_selection_policy: str
    checkpoint_selection_review_status: str
    checkpoint_selection_semantics: str
    checkpoint_selection_box_component_weight: float
    checkpoint_selection_mask_component_weight: float
    primary_scientific_reporting_metric: str
    selection_metric_equals_primary_reporting_metric: bool
    checkpoint_selection_rationale: tuple[str, ...]
    checkpoint_selection_future_constraint: str
    metrics: SegmentationMetricHierarchy
    rare_class: str
    rare_class_limitation: str
    test_policy: str

    def as_dict(self) -> dict[str, Any]:
        """Serialise the protocol for hashing and reporting.

        Returns:
            A JSON-serialisable mapping of the protocol content.
        """
        return {
            "schema_version": self.schema_version,
            "experiment_id": self.experiment_id,
            "task": self.task,
            "description": self.description,
            "architecture": self.architecture,
            "model": self.model,
            "weights": self.weights,
            "weight_identifier": self.weight_identifier,
            "fallback_architecture": self.fallback_architecture,
            "fallback_status": self.fallback_status,
            "canonical_ground_truth": self.canonical_ground_truth,
            "dataset_config": self.dataset_config,
            "adapter": self.adapter,
            "class_map_sha256": self.class_map_sha256,
            "split_assignment_sha256": self.split_assignment_sha256,
            "splits": list(self.splits),
            "seed": self.seed,
            "device_requirement": self.device_requirement,
            "training": self.training,
            "segmentation_arguments": self.segmentation_arguments,
            "augmentation_policy": self.augmentation_policy,
            "augmentation_arguments": self.augmentation_arguments,
            "batch_decision": self.batch_decision,
            "checkpoint_selection": self.checkpoint_selection,
            "checkpoint_selection_policy": self.checkpoint_selection_policy,
            "checkpoint_selection_review_status": self.checkpoint_selection_review_status,
            "checkpoint_selection_semantics": self.checkpoint_selection_semantics,
            "checkpoint_selection_box_component_weight": (
                self.checkpoint_selection_box_component_weight
            ),
            "checkpoint_selection_mask_component_weight": (
                self.checkpoint_selection_mask_component_weight
            ),
            "primary_scientific_reporting_metric": self.primary_scientific_reporting_metric,
            "selection_metric_equals_primary_reporting_metric": (
                self.selection_metric_equals_primary_reporting_metric
            ),
            "checkpoint_selection_rationale": list(self.checkpoint_selection_rationale),
            "checkpoint_selection_future_constraint": self.checkpoint_selection_future_constraint,
            "metrics": self.metrics.as_dict(),
            "rare_class": self.rare_class,
            "rare_class_limitation": self.rare_class_limitation,
            "test_policy": self.test_policy,
        }

    def fingerprint(self) -> str:
        """Hash the protocol, so a result can name the rules that produced it.

        Returns:
            A SHA-256 hex digest over the protocol content only.
        """
        return digest(self.as_dict())

    def training_arguments(self) -> dict[str, Any]:
        """Assemble the complete argument set the framework will be given.

        The three declared blocks are disjoint by construction - the loader
        refuses an argument that appears in more than one - so this is a merge
        rather than a precedence decision.

        Returns:
            Every framework argument the protocol fixes, excluding the ones that
            name a location on this machine.
        """
        arguments: dict[str, Any] = {
            key: value for key, value in self.training.items() if key != "augmentation"
        }
        arguments.update(self.segmentation_arguments)
        arguments.update(self.augmentation_arguments)
        arguments["seed"] = self.seed
        return arguments


def _contains_forbidden_split(value: Any) -> bool:
    """Report whether a parsed value mentions the protected split.

    Args:
        value: Any parsed configuration value.

    Returns:
        ``True`` when the protected split appears as a string or a key.
    """
    if isinstance(value, str):
        return value.strip().lower() == FORBIDDEN_SPLIT
    if isinstance(value, Mapping):
        return any(
            _contains_forbidden_split(key) or _contains_forbidden_split(item)
            for key, item in value.items()
        )
    if isinstance(value, Sequence) and not isinstance(value, (str, bytes)):
        return any(_contains_forbidden_split(item) for item in value)
    return False


